import assert from "node:assert/strict";

export async function exerciseWindowFullscreen({page, expect, fixture, nav}) {
  const button = (name, root = page) => root.getByRole("button", {name, exact: true});
  const full = button("Enter full screen");
  const exit = button("Exit full screen");
  const native = () => page.evaluate(() => !!fixture.windowFullscreen);
  const ssh = page.locator(".terminal-pane.focused:visible .xterm-helper-textarea");
  await button(fixture.state_load.hosts[0].name, page.locator(".connections-grid")).click();
  await expect(ssh).toBeFocused();
  await full.click();
  await expect.poll(native).toBe(true);
  await expect(ssh).toBeFocused();
  const views = page.getByRole("group", {name:"Session view"});
  await button("SFTP", views).click();
  await expect(exit).toBeVisible();
  await button("Database", views).click();
  await expect(exit).toBeVisible();
  await page.keyboard.press("F11");
  await expect.poll(native).toBe(false);
  await button("Sidebar").click();
  await nav("Serial").click();
  await button("New serial session").click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Serial port", {exact:true}).selectOption("port:COM7");
  await button("Connect", dialog).click();
  const serial = page.getByRole("region", {name:"Serial terminal COM7"});
  await expect(serial.getByRole("status")).toHaveText("Connected");
  await full.click();
  await expect.poll(native).toBe(true);
  await expect(serial.locator(".xterm-helper-textarea")).toBeFocused();
  await page.keyboard.type("serial-test");
  await page.keyboard.press("Escape");
  await expect.poll(native).toBe(true);
  await expect.poll(() => page.evaluate(() => fixture.serialOutput)).toContain("serial-test");
  await exit.click();
  await expect.poll(native).toBe(false);
  await expect(serial.locator(".xterm-helper-textarea")).toBeFocused();
  await nav("Databases").click();
  await page.keyboard.press("F11");
  await expect(exit).toBeVisible();
  await button("Sidebar").click();
  await nav("Hosts").click();
  await exit.click();
  await expect.poll(native).toBe(false);
  const connections = await page.evaluate(() => fixture.calls.map(c => c.args?.action));
  assert.equal(connections.filter(action => action === "ssh_connect").length, 1);
  assert.equal(connections.filter(action => action === "serial_open").length, 1);
  assert.ok(!connections.includes("serial_close") && !connections.includes("ssh_disconnect"));
}
